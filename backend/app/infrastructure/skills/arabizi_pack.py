"""Loads the generated Lebanese Arabizi pack into the Standard assistant's Arabizi skill (2026-11-23).

The pack (backend/app/assistant_assets/arabizi/) is generated by the fine-tuning workstream from the owner's rulings
(research/dataset/arabizi_pack.py) and never edited by hand. It is read once per process, whole, in a fixed order:
- style_guide.md: her rulings, word for word;
- forms.json: reply forms per gender, accepted and rejected spellings, the words only said to a man or a woman;
- examples.jsonl: approved answers, each with the question and the result it was written from;
- VERSION: the generator's version and the hashes of its sources.

EXPECTED_FINGERPRINT pins the exact pack this code was reviewed with (a SHA-256 of those four files). A regenerated
pack, or one edited by hand, does not match: Standard then reports itself unavailable instead of answering without
her rulings or with unreviewed ones. After a regeneration, review the new pack and update the fingerprint (the test
tests/infrastructure/skills/test_arabizi_pack.py prints the new value).
"""

import hashlib
import json
from pathlib import Path

from app.application.assistant.standard_skills import ArabiziPack, Skill
from app.domain.assistant.arabizi import ArabiziWords

PACK_DIR = Path(__file__).resolve().parents[2] / "assistant_assets" / "arabizi"
FILES = ("VERSION", "style_guide.md", "forms.json", "examples.jsonl")
EXPECTED_FINGERPRINT = "5b8f7aef830e4c79235d514bccba2bf42ac55797b90857ea14234813faf8d2ba"  # pack of 2026-11-23

_INTRO = """These are the rulings of the app's owner, the native Lebanese Arabizi speaker, exported from tables she
approved. Follow them for every Arabizi or mixed reply. Do not invent, extend or "correct" Arabizi beyond them; never
change the user's own spellings or a shop or item name. Use the reply forms for the gender the turn's context gives
(man, woman or neutral; neutral avoids addressing "you"). The approved examples show the register and phrasing; each
has the question, the result it was written from and the approved reply."""


class ArabiziPackUnavailable(RuntimeError):
    pass


def fingerprint(directory: Path = PACK_DIR) -> str:
    digest = hashlib.sha256()
    for name in FILES:
        digest.update(name.encode() + b"\0" + (directory / name).read_bytes() + b"\0")
    return digest.hexdigest()


def load_arabizi_pack(directory: Path = PACK_DIR, expected: str | None = None) -> ArabiziPack:
    """Raises ArabiziPackUnavailable if a file is missing, unreadable, or not the reviewed pack."""
    expected = expected or EXPECTED_FINGERPRINT
    try:
        found = fingerprint(directory)
        if found != expected:
            raise ArabiziPackUnavailable(f"The Arabizi pack is not the reviewed one (fingerprint {found})")
        version = (directory / "VERSION").read_text(encoding="utf-8")
        style_guide = _without_generator_note((directory / "style_guide.md").read_text(encoding="utf-8"))
        forms = json.loads((directory / "forms.json").read_text(encoding="utf-8"))
        lines = (directory / "examples.jsonl").read_text(encoding="utf-8").splitlines()
        examples = [json.loads(line) for line in lines[1:] if line.strip()]  # the first line is a header
        spellings, answer_words = forms["spellings"], forms["answer_words"]
        words = ArabiziWords(frozenset(spellings["rejected_all"]), frozenset(answer_words["man_only"]),
                             frozenset(answer_words["woman_only"]))  # fmt: skip
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise ArabiziPackUnavailable(f"The Arabizi pack could not be read ({type(exc).__name__})") from exc
    if not style_guide.strip() or not examples or not words.rejected:
        raise ArabiziPackUnavailable("The Arabizi pack is incomplete")

    generator = next((line.split(" ", 1)[1] for line in version.splitlines() if line.startswith("generator ")), "?")
    forms_text = json.dumps({k: v for k, v in forms.items() if not k.startswith("_")}, ensure_ascii=False,
                            separators=(",", ":"))  # fmt: skip
    example_lines = "\n".join(
        json.dumps({key: example.get(key) for key in ("question", "result", "reply", "language", "gender")},
                   ensure_ascii=False, separators=(",", ":"))
        for example in examples
    )  # fmt: skip
    text = (f"{_INTRO}\n\n### Style guide (style_guide.md)\n{style_guide.strip()}\n\n### Reply forms and spellings "
            f"(forms.json)\n{forms_text}\n\n### Approved examples (examples.jsonl)\n{example_lines}")  # fmt: skip
    skill = Skill("lebanese_arabizi", f"arabizi-pack-generator-{generator}-{found[:12]}", text)
    return ArabiziPack(skill, words)


def _without_generator_note(text: str) -> str:
    """The style guide without the generator's leading HTML comment (a note for people, not a ruling)."""
    lines = text.splitlines()
    while lines and lines[0].strip().startswith("<!--") and lines[0].strip().endswith("-->"):
        lines.pop(0)
    return "\n".join(lines)
