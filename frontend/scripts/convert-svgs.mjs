// Converts the Figma-exported SVGs in assets/icons and assets/wordmark into plain data that
// src/shared/ui/art/ArtSvg.tsx draws with react-native-svg.
//
// Run it again whenever an SVG changes:  npm run convert-svgs
//
// Every element is kept (gradients, masks, paths, circles, rects), so the printed fade of D026 and
// D029 survives the conversion. "currentColor" is kept too: ArtSvg sets the colour on the <Svg>.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/shared/ui/art');

const KNOWN_TAGS = new Set(['svg', 'defs', 'linearGradient', 'stop', 'mask', 'rect', 'path', 'circle']);
const SKIPPED_TAGS = new Set(['title']);
// Attributes that only matter in a browser (ArtSvg sets the accessibility props itself).
const SKIPPED_ATTRS = new Set(['xmlns', 'aria-hidden', 'aria-label', 'role']);
const NUMERIC = /^-?\d+(\.\d+)?$/;

function camel(name) {
  return name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
}

function parseAttrs(source) {
  const attrs = {};
  // Names may hold digits (x1, y1, x2, y2 give a gradient its direction).
  for (const [, name, value] of source.matchAll(/([a-zA-Z][a-zA-Z0-9:-]*)="([^"]*)"/g)) {
    attrs[name] = value;
  }
  return attrs;
}

/** A tiny parser for the regular SVGs Figma exports here (no text nodes, no comments, no CDATA). */
function parse(svg, file) {
  const rootNode = { tag: '#root', props: {}, children: [] };
  const stack = [rootNode];
  for (const [, closing, tag, attrSource, selfClosing] of svg.matchAll(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g)) {
    if (closing) {
      stack.pop();
      continue;
    }
    if (!KNOWN_TAGS.has(tag) && !SKIPPED_TAGS.has(tag)) {
      throw new Error(`${file}: unsupported element <${tag}>; add it to KNOWN_TAGS and to ArtSvg`);
    }
    const attrs = parseAttrs(attrSource);
    const node = { tag, props: {}, children: [] };
    for (const [name, value] of Object.entries(attrs)) {
      if (SKIPPED_ATTRS.has(name)) continue;
      node.props[camel(name)] = NUMERIC.test(value) ? Number(value) : value;
    }
    const parent = stack[stack.length - 1];
    if (!SKIPPED_TAGS.has(tag)) parent.children.push(node);
    if (!selfClosing) stack.push(SKIPPED_TAGS.has(tag) ? { tag, props: {}, children: [] } : node);
  }
  const [svgNode] = rootNode.children;
  if (!svgNode || svgNode.tag !== 'svg') throw new Error(`${file}: no <svg> root`);
  return svgNode;
}

function load(path) {
  return parse(readFileSync(path, 'utf8'), path);
}

const HEADER = `// GENERATED by scripts/convert-svgs.mjs from the SVGs in assets/. Do not edit by hand:
// change the SVG (drawn in Figma) and run \`npm run convert-svgs\`.
import type { ArtNode } from './ArtSvg';
`;

// Icons: every <name>.svg has a <name>-printed.svg twin (D025, D026).
const iconDir = join(root, 'assets/icons');
const iconNames = readdirSync(iconDir)
  .filter((file) => file.endsWith('.svg') && !file.endsWith('-printed.svg'))
  .map((file) => file.replace(/\.svg$/, ''))
  .sort();
const icons = {};
for (const name of iconNames) {
  icons[name] = {
    clean: load(join(iconDir, `${name}.svg`)),
    printed: load(join(iconDir, `${name}-printed.svg`)),
  };
}
writeFileSync(
  join(outDir, 'iconArt.generated.ts'),
  `${HEADER}
export const iconNames = ${JSON.stringify(iconNames)} as const;

export type IconName = (typeof iconNames)[number];

export const iconArt: Record<IconName, { clean: ArtNode; printed: ArtNode }> = ${JSON.stringify(icons, null, 1)};
`,
);

// Wordmark: large (48 px type, launch and sign in) and small (20 px type, the Home header) (D029).
const wordmarkDir = join(root, 'assets/wordmark');
const wordmarks = {
  large: load(join(wordmarkDir, 'fatourati-large.svg')),
  small: load(join(wordmarkDir, 'fatourati-small.svg')),
};
writeFileSync(
  join(outDir, 'wordmarkArt.generated.ts'),
  `${HEADER}
export const wordmarkArt: Record<'large' | 'small', ArtNode> = ${JSON.stringify(wordmarks, null, 1)};
`,
);

console.log(`Converted ${iconNames.length} icons (clean + printed) and 2 wordmarks into ${outDir}`);
