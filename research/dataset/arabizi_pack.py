def _words(text: str, words) -> list[str]:
    return [w for w in words if re.search(rf"(?<!\w){re.escape(w)}(?!\w)", text, re.IGNORECASE)]


def rejected_words() -> tuple[str, ...]:
    code = (*batch5_build.REJECTED, *answers_build.REJECTED, *months._ALSO_REJECTED)
    return tuple(dict.fromkeys((*code, *(form for form, _ in NEVER_IN_RULINGS))))


def wrong_gender(text: str, gender: str) -> list[str]:
    """Words in an Arabizi reply that address the other gender (both, when the gender is not given)."""
    man = (*answers_build.MAN_ONLY, *genders.MASCULINE_WORDS)
    wrong = {"woman": man, "man": answers_build.WOMAN_ONLY, "not given": (*man, *answers_build.WOMAN_ONLY)}[gender]
    return _words(text, tuple(dict.fromkeys(wrong)))


def wrong_speaker(question: str, gender: str) -> list[str]:
    """The user's own "I" words of the other gender (a man's question must never say def3a)."""
    if gender == "man":
        return _words(question, tuple(w for w, _ in genders.SPEAKER_WORDS))
    if gender == "woman":
        return _words(question, tuple(m for _, m in genders.SPEAKER_WORDS))
    return []


def _parse(row: dict) -> dict:
    prompt, reply = row["messages"][0]["content"], row["messages"][1]["content"]
    body = prompt.split("\n\nToday:", 1)[1]
    lines = body.split("\n")
    field = lambda name: next((l.split(": ", 1)[1] for l in lines if l.startswith(name + ": ")), None)  # noqa: E731
    receipts = field("Number of receipts used")
    labels = row["labels"]
    return {"question": fixes.fixed_question(field("Question")), "today": lines[0].strip(),
            "result": {"columns": field("Result columns").split(" | "),
                       "rows": [l.split(": ", 1)[1].split(" | ") for l in lines if l.startswith("Row: ")],
                       "column_totals": field("Column totals"), "receipts": int(receipts) if receipts else None},
            "reply": reply, "language": labels["language"], "gender": labels["gender"], "result_kind": labels["result"],
            "source_template": labels["source_template"], "job_id": labels["job_id"]}  # fmt: skip


def near_test(question: str, tests: tuple[str, ...]) -> bool:
    """checks.near_duplicate's test (difflib ratio >= checks.NEAR_DUPLICATE on normalized text), with difflib's upper
    bounds tried first: the same answer, faster."""
    mine = checks.normalized(question)
    for test in tests:
        matcher = difflib.SequenceMatcher(None, mine, test)  # the order near_duplicate uses
        if (matcher.real_quick_ratio() >= checks.NEAR_DUPLICATE and matcher.quick_ratio() >= checks.NEAR_DUPLICATE
                and matcher.ratio() >= checks.NEAR_DUPLICATE):
            return True
    return False


def candidates(rows: list[dict], test_questions: tuple[str, ...]) -> list[dict]:
    """The stored answers fit to show: no rejected spelling, no other gender's words, not near a test question."""
    tests = tuple(dict.fromkeys(checks.normalized(q) for q in test_questions))
    rejected, found, seen = rejected_words(), [], set()
    for row in rows:
        if row["labels"].get("kind") != "answer":
            continue
        example = _parse(row)
        question, reply = example["question"], example["reply"]
        if checks.normalized(question) in seen or _words(question + "\n" + reply, rejected):
            continue
        if example["language"] != "english" and (wrong_gender(reply, example["gender"])
                                                 or wrong_speaker(question, example["gender"])):
            continue
        if checks.normalized(question) in tests or near_test(question, tests):
            continue
        seen.add(checks.normalized(question))
        found.append(example)
    return found


def pick(found: list[dict]) -> list[dict]:
    """About 100, by language quota; within a language one per result kind in turn (kinds in a seeded order), and
    within a kind the next gender and a template not yet shown, so the picks vary."""
    rng, chosen = random.Random(SEED), []
    for language, quota in EXAMPLES.items():
        groups = defaultdict(list)
        for example in sorted((e for e in found if e["language"] == language), key=lambda e: e["job_id"]):
            groups[example["result_kind"]].append(example)
        kinds = sorted(groups)
        rng.shuffle(kinds)
        for group in groups.values():
            rng.shuffle(group)
        used, turn, taken = defaultdict(set), 0, 0
        while taken < quota and any(groups.values()):
            for kind in kinds:
                if taken >= quota or not groups[kind]:
                    continue
                want = GENDERS[turn % len(GENDERS)]
                group = groups[kind]
                best = min(range(len(group)), key=lambda i: (group[i]["gender"] != want,
                                                             group[i]["source_template"] in used[kind], i))
                example = group.pop(best)
                used[kind].add(example["source_template"])
                chosen.append(example)
                turn, taken = turn + 1, taken + 1
    return chosen


def examples(rows: list[dict], test_questions: tuple[str, ...]) -> list[dict]:
    return pick(candidates(rows, test_questions))


# --- the pack -------------------------------------------------------------------------------------------------------

def _json(data) -> str:
    return json.dumps(data, ensure_ascii=False, indent=1) + "\n"


def sources(with_word_list: bool = True) -> dict[str, Path]:
    found = {"notes": NOTES_FILE, "phrasing": PHRASING_FILE, "answers": ANSWERS_FILE}
    found |= {f"code/{p.name}": p for p in CODE_SOURCES} | {f"evaluation/{p.name}": p for p in EVALUATION_SOURCES}
    if with_word_list:
        found["word_list"] = WORD_LIST_FILE
    return found


def pack(with_word_list: bool = True) -> dict[str, str]:
    """Every pack file's text, from the sources as they are now."""
    paths = sources(with_word_list)
    texts = {name: _text(path) for name, path in paths.items()}
    notes, phrasing = texts["notes"], texts["phrasing"]
    rows = [json.loads(line) for line in texts["answers"].split("\n") if line.strip()]
    picked = examples(rows, build.test_questions(None))
    header = {"_generated": HEADER, "count": len(picked),
              "about": "Stored answer examples (data/batch5/answers_train.jsonl), approved patterns; the question "
                       "with the mix's question fixes. result: the query result the answer was written from."}
    copy = "<!-- {header}. Verbatim copy of {name} (line endings LF). -->\n\n"
    files = {
        "rulings_source.md": copy.format(header=HEADER, name=NOTES_FILE.name) + notes,
        "phrasing_source.md": copy.format(header=HEADER, name=PHRASING_FILE.name) + phrasing,
        "style_guide.md": style_guide(notes, phrasing),
        "forms.json": _json(forms_data(notes)),
        "examples.jsonl": "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in [header, *picked]),
    }
    if with_word_list:
        files[WORD_LIST] = copy.format(header=HEADER, name=WORD_LIST_FILE.name) + texts["word_list"]
    hashes = {name: hashlib.sha256(text.encode("utf-8")).hexdigest() for name, text in texts.items()}
    total = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode("utf-8")).hexdigest()
    files["VERSION"] = (f"# {HEADER}\ngenerator {GENERATOR_VERSION}\nsources {total}\n"
                        + "".join(f"{name} {digest}\n" for name, digest in sorted(hashes.items())))
    return files


def differences(files: dict[str, str], pack_dir: Path = PACK_DIR) -> list[str]:
    found = []
    for name, text in files.items():
        path = pack_dir / name
        if not path.exists():
            found.append(f"{name}: missing")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            found.append(f"{name}: differs")
    if WORD_LIST not in files and (pack_dir / WORD_LIST).exists():
        found.append(f"{WORD_LIST}: present, but the word list is off (use --with-word-list)")
    return found


def write(files: dict[str, str], pack_dir: Path = PACK_DIR) -> None:
    pack_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (pack_dir / name).write_text(text, encoding="utf-8", newline="\n")
    if WORD_LIST not in files and (pack_dir / WORD_LIST).exists():
        (pack_dir / WORD_LIST).unlink()  # a generated file: the word list is off


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="write the pack")
    action.add_argument("--check", action="store_true", help="exit 1 if the tracked pack is not current")
    parser.add_argument("--without-word-list", action="store_true",
                        help="leave her word list out (it is in by default: her OK of 2026-11-23)")
    args = parser.parse_args(argv)
    try:
        files = pack(not args.without_word_list)
    except PackError as exc:
        print(f"arabizi pack: {exc}", file=sys.stderr)
        return 2
    if args.write:
        write(files)
        print(f"wrote {len(files)} files to {PACK_DIR}")
        return 0
    found = differences(files)
    for line in found:
        print(f"arabizi pack not current: {line}", file=sys.stderr)
    if not found:
        print("arabizi pack is current")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
