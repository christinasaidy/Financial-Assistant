class PackError(ValueError):
    """A source is missing, or a quote is no longer in her notes."""


def _text(path: Path) -> str:
    if not path.exists():
        raise PackError(f"missing source: {path}")
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


