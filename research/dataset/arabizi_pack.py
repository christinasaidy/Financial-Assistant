def _dated_lines(text: str) -> list[tuple[str, str]]:
    """Each line of a note with its date: a bullet's own "(YYYY-MM-DD", else the dated heading above it; an indented
    line takes the line before's; an undated plain line (Why / How to apply) is "undated"."""
    found, heading, previous = [], "undated", "undated"
    for line in text.split("\n"):
        date = re.search(r"\((\d{4}-\d\d-\d\d)", line)
        if line.startswith("  ") and found:
            dated = previous
        elif line.startswith("- "):
            dated = date.group(1) if date and line.startswith("- (") else heading
        elif date:
            dated = heading = date.group(1)
        else:
            dated = "undated"
        found.append((line, dated))
        previous = dated
    return found


def quote_date(quote: str, text: str) -> str:
    """The date of the one note line that holds the quote; PackError when no line, or more than one, holds it."""
    lines = [dated for line, dated in _dated_lines(text) if quote in line]
    if len(lines) != 1:
        raise PackError(f"quote found on {len(lines)} lines of her notes (need exactly 1): {quote!r}")
    return lines[0]


def _code_rules() -> list[str]:
    """The rules the code applies, one line each (the batch-1 ones from batch1_cleanup's own list)."""
    doc = batch1_cleanup.__doc__.split("Rules (applied in this order")[1].split("\nLines that contain")[0]
    bullets, current = [], None
    for line in doc.split("\n")[1:]:
        if line.startswith("- "):
            current = [line[2:].strip()]
            bullets.append(current)
        elif line.startswith("  ") and current is not None:
            current.append(line.strip())
    in_mix = {fn for fn in fixes.QUESTION_RULES}
    names = dict(batch1_cleanup.RULES)
    rules = ["Batch-1 rules (2026-11-21, batch1_cleanup.py; marked * = also applied to every stored question by "
             "fixes.QUESTION_RULES):"]
    for bullet in bullets:
        text = " ".join(bullet)
        if text.endswith("see below."):
            continue
        name = text.split(":")[0].split(" ")[0]
        star = "*" if names.get(name) in in_mix else ""
        rules.append(f"  - {star}{text}")
    words = "; ".join(f"\"{_plain(p.pattern)}\" -> \"{r}\"" for p, r in fixes.QUESTION_WORDS)
    rules.append(f"Question words (2026-11-22, fixes.QUESTION_WORDS): {words}.")
    rules.append(f"Single letters (2026-11-22, fixes.SINGLE_LETTERS): {len(fixes.SINGLE_LETTERS)} words written doubled "
                 "in most questions are written single in about half of them (forms.json fixes.single_letters).")
    spellings = "; ".join(f"\"{_plain(p.pattern)}\" -> \"{s}\" in about 1 in {n}" for p, s, _, n in fixes.HER_SPELLINGS)
    rules.append(f"Her everyday spellings (2026-11-22 / 23, fixes.HER_SPELLINGS): {spellings} of the questions with the "
                 "word. Replies: fawatirak / fawatirik as approved, fwatirak / fwatirik in about 60% "
                 "(fixes.reply_spellings, 2026-11-23).")
    numbers = ", ".join(f"{d} -> {w}" for d, w in fixes._IN_WORDS.items())
    rules.append(f"Numbers in words before a period word (2026-11-23, fixes.numbers_in_words): {numbers} (5 is "
                 "\"khamst\" in about 1 of 5), in about half of the Arabizi questions (forms.json fixes.numbers_in_words).")
    return rules


def _plain(pattern: str) -> str:
    return re.sub(r"\(\?<!\\w\)|\(\?!\\w\)|\(\?=\\w\)", "", pattern).replace("(", "").replace(")", "")


def style_guide(notes: str, phrasing: str) -> str:
    out = [f"<!-- {HEADER} -->", "", "# Lebanese Arabizi style guide", "",
           "Quotes are Christina's rulings, word for word, tagged with the date of the note they come from "
           "(rulings_source.md and phrasing_source.md are the full notes). \"[flagged: ...]\" marks a ruling kept as "
           "written that needs her decision or sits next to another ruling. The reply forms, speaker words, "
           "accepted and rejected spellings and number words are in forms.json; approved answers in examples.jsonl "
           "(its first line is a header).", ""]
    sources = {N: notes, P: phrasing}
    for number, (heading, intro, quotes) in enumerate(SECTIONS, 1):
        out += [f"## {number}. {heading}", ""]
        if intro:
            out += [intro, ""]
        for source, quote, mark in quotes:
            date = quote_date(quote, sources[source])
            where = "" if source == N else " (phrasing)"
            flag = "" if not mark else f" [{mark}]" if mark.startswith("resolved") else f" [flagged: {mark}]"
            out.append(f"- ({date}{where}) {quote}{flag}")
        if heading.startswith("Spelling"):
            out += ["", "Applied by code when the training mix is built (one line each):", ""]
            out += [f"- {rule}" if not rule.startswith("  ") else rule for rule in _code_rules()]
        out.append("")
    return "\n".join(out)


